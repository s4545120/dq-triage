#!/usr/bin/env python3
"""Generate the migration that replaces the mock register with the key attributes.

    python3 sql/migrate_key_attributes.py --catalog workspace --schema dq_triage --prefix dq_

Writes sql/out/migrate_key_attributes.sql. Taken as a decision on 2026-10-12: "no more
mockup data for attributes and rules". Six parts, then read-only checks.

PART 1 -- RETIRE EVERY ELEMENT THAT IS NOT A KEY ATTRIBUTE. One statement: a new
cde_version, status 'retired', for the latest version of every element whose id does not
start KA_ and is not retired already. Bindings are left on the retired version as
history; v_binding_current reads registered elements only, so nothing binds them now.

PART 2 -- RETIRE EVERY RULE ON THEM. Same shape on the rule register: every current rule
not naming a key attribute. promoted_by / promoted_at carry forward, as every retirement
here has done.

PART 3 -- DECOMMISSION EVERY MONITORED TABLE THAT HOLDS NO KEY ATTRIBUTE. A new
table_version, status 'retired', with a note (the table refuses a stop without one) and
the slice in force carried forward. The mock tables and anything onboarded for testing.

Nothing before these parts is touched. check_run, cohorts, the disposition register,
threshold and tolerance history all stay, as history about rules that are now retired.

PART 4 -- 22 KEY ATTRIBUTES, version 1, one binding each, on the prod.* source tables.
PART 5 -- THE MIGRATION RULES, all shadow, rule_version 1, plus a universe rule set for
any attribute they leave uncovered (none today).
PART 6 -- SELECT THE FIVE SOURCE TABLES so the daily check job takes them as its worklist.
This workspace has no prod catalog, so until it does every check on them is recorded as
an error, and discovery skips them (onboarding/onboard.py says so in its output).

RE-RUNNABLE. Parts 1-3 select only what is not retired yet, and parts 4-6 are guarded
by NOT EXISTS. appendOnly means a duplicate could never be removed, so a second run
inserts nothing.

NOT RUN by this script. There is no rollback: un-retiring is another version.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).parent.parent
OUT = pathlib.Path(__file__).parent / "out"
sys.path.insert(0, str(ROOT / "key_attributes"))
sys.path.insert(0, str(pathlib.Path(__file__).parent))

import register as ka  # noqa: E402
import universe  # noqa: E402
from migrate_cde_scope import CDE_COLUMNS, RULE_COLUMNS, lit  # noqa: E402

MONITORED_COLUMNS = ["target_table", "table_version", "table_code", "row_key", "owner_group",
                     "business_domain", "schedule_group", "scan_mode", "status",
                     "effective_from", "selected_by", "note", "slice_filter", "slice_spec",
                     "slice_version", "slice_change", "slice_proposed_filter",
                     "slice_proposed_spec", "slice_proposed_by"]
KA_LIKE = "'KA\\\\_%'"          # SQL text 'KA\\_%': an underscore matched literally

RETIRE_ELEMENT_NOTE = (
    "Retired 2026-10-12 with the rest of the mock register: the register is now the key "
    "attributes from DQ_ATTR_PRIORI.xlsx. Runs and problems before this date stand as "
    "history.")
RETIRE_RULE_NOTE = (
    "Retired 2026-10-12: its element was mock data, retired with the rest of the mock "
    "register in favour of the key attributes and their migration rules.")
RETIRE_TABLE_NOTE = (
    "Decommissioned 2026-10-12: it holds no key attribute. The register moved off the mock "
    "data to the key attributes from DQ_ATTR_PRIORI.xlsx.")


def _null(c: str) -> str:
    return {"promoted_at": "CAST(NULL AS TIMESTAMP)", "slice_version": "CAST(NULL AS INT)"}.get(
        c, "CAST(NULL AS STRING)")


def build(catalog: str, schema: str, prefix: str) -> tuple[list[str], list[tuple[str, str, str]]]:
    q = f"{catalog}.{schema}.{prefix}"
    cde, cde_cur = f"{q}config_cde_registry", f"{q}config_v_cde_registry_current"
    reg, reg_cur = f"{q}config_rule_registry", f"{q}config_v_rule_registry_current"
    mon, mon_cur = f"{q}config_monitored_table", f"{q}config_v_monitored_table_current"
    cov = f"{q}results_v_cde_coverage"
    rules = universe.all_rules()
    ka_tables = ", ".join(lit(t) for t in ka.TABLES)

    stmts: list[tuple[str, str, str]] = []
    lines = [
        "-- =====================================================================",
        "-- migrate_key_attributes.sql — GENERATED by sql/migrate_key_attributes.py. Do not edit.",
        f"-- target: {catalog}.{schema}, prefix {prefix}",
        "--",
        "-- Retires the mock register (every element, rule and monitored table that is",
        "-- not a key attribute), then registers the 22 key attributes from",
        f"-- DQ_ATTR_PRIORI.xlsx and their {len(rules)} migration rules, all in SHADOW, and",
        "-- selects their five prod.* source tables. Re-running inserts nothing.",
        "-- See the generator's docstring.",
        "-- =====================================================================",
    ]

    def add(label: str, kind: str, sql: str, comment: list[str] | None = None) -> None:
        stmts.append((label, kind, sql))
        lines.extend(["", *(comment or []), sql + ";"])

    lines += ["", "-- Step 0 — before. EXPECTED: the mock register's counts, and 0 key attributes."]
    add("0a", "check",
        f"SELECT CASE WHEN cde_id LIKE {KA_LIKE} THEN 'key attribute' ELSE 'mock' END AS kind,\n"
        f"       status, COUNT(*) AS elements\nFROM   {cde_cur}\nGROUP  BY 1, 2 ORDER BY 1, 2")
    add("0b", "check",
        f"SELECT status, COUNT(*) AS rules FROM {reg_cur} GROUP BY status ORDER BY status")
    add("0c", "check",
        f"SELECT target_table, table_version, status FROM {mon_cur} ORDER BY target_table")

    # --- Part 1 -----------------------------------------------------------------------
    lines += ["", "-- =====================================================================",
              "-- Part 1 — retire every element that is not a key attribute",
              "-- ====================================================================="]
    sel = []
    for c in CDE_COLUMNS:
        sel.append({"cde_version": "c.cde_version + 1", "status": "'retired'",
                    "effective_from": "current_timestamp()", "registered_at": "current_timestamp()",
                    "registered_by": "current_user()", "note": lit(RETIRE_ELEMENT_NOTE)}.get(c, f"c.{c}"))
    add("retire:elements", "insert",
        f"INSERT INTO {cde} ({', '.join(CDE_COLUMNS)})\n"
        f"SELECT {', '.join(sel)}\n"
        f"FROM   {cde} c\n"
        f"JOIN   (SELECT cde_id AS id, max(cde_version) AS v FROM {cde} GROUP BY cde_id) m\n"
        f"  ON   m.id = c.cde_id AND m.v = c.cde_version\n"
        f"WHERE  c.status <> 'retired' AND c.cde_id NOT LIKE {KA_LIKE}")

    # --- Part 2 -----------------------------------------------------------------------
    lines += ["", "-- =====================================================================",
              "-- Part 2 — retire every rule that does not name a key attribute",
              "-- ====================================================================="]
    sel = []
    for c in RULE_COLUMNS:
        sel.append({"rule_version": "r.rule_version + 1", "status": "'retired'",
                    "effective_from": "current_timestamp()", "created_at": "current_timestamp()",
                    "created_by": "current_user()", "note": lit(RETIRE_RULE_NOTE)}.get(c, f"r.{c}"))
    add("retire:rules", "insert",
        f"INSERT INTO {reg} ({', '.join(RULE_COLUMNS)})\n"
        f"SELECT {', '.join(sel)}\n"
        f"FROM   {reg} r\n"
        f"JOIN   (SELECT rule_id AS id, max(rule_version) AS v FROM {reg} GROUP BY rule_id) m\n"
        f"  ON   m.id = r.rule_id AND m.v = r.rule_version\n"
        f"WHERE  r.status <> 'retired' AND coalesce(r.cde_id, '') NOT LIKE {KA_LIKE}")

    # --- Part 3 -----------------------------------------------------------------------
    lines += ["", "-- =====================================================================",
              "-- Part 3 — decommission every monitored table holding no key attribute",
              "-- ====================================================================="]
    pending = "(t.slice_proposed_by IS NOT NULL AND coalesce(t.slice_change, '') NOT IN ('approved', 'rejected'))"
    sel = []
    for c in MONITORED_COLUMNS:
        if c in ("slice_proposed_filter", "slice_proposed_spec", "slice_proposed_by"):
            sel.append(f"CASE WHEN {pending} THEN t.{c} END")
            continue
        sel.append({"table_version": "t.table_version + 1", "status": "'retired'",
                    "effective_from": "current_timestamp()", "selected_by": "current_user()",
                    "note": lit(RETIRE_TABLE_NOTE), "slice_change": "CAST(NULL AS STRING)"}.get(c, f"t.{c}"))
    add("retire:tables", "insert",
        f"INSERT INTO {mon} ({', '.join(MONITORED_COLUMNS)})\n"
        f"SELECT {', '.join(sel)}\n"
        f"FROM   {mon} t\n"
        f"JOIN   (SELECT target_table AS id, max(table_version) AS v FROM {mon} GROUP BY target_table) m\n"
        f"  ON   m.id = t.target_table AND m.v = t.table_version\n"
        f"WHERE  t.status <> 'retired' AND t.target_table NOT IN ({ka_tables})",
        ["-- The slice in force carries forward; a pending proposal only while pending",
         "-- (dq_app/domain/slices.carry_forward says the same)."])

    # --- Part 4 -----------------------------------------------------------------------
    lines += ["", "-- =====================================================================",
              f"-- Part 4 — {len(ka.KEY_ATTRIBUTES)} key attributes, version 1",
              "-- ====================================================================="]
    for a in ka.KEY_ATTRIBUTES:
        binding = ("array(named_struct('target_table', {t}, 'target_column', {c}, "
                   "'populated_when', {p}, 'expected_scope_filter', CAST(NULL AS STRING), "
                   "'binding_status', 'bound', 'discovered_by', 'manual', "
                   "'confidence', CAST(1.0 AS DOUBLE)))").format(
            t=lit(a.table), c=lit(a.column),
            p=lit(a.populated_when) if a.populated_when else "CAST(NULL AS STRING)")
        note = (f"Registered 2026-10-12 from {ka.SHEET}. Criticality '{ka.CRITICALITY}' is the "
                "same for every key attribute because the sheet ranks none of them; no "
                "tolerance is declared yet.")
        vals = {"cde_id": lit(a.cde_id), "cde_version": "1", "cde_name": lit(a.name),
                "business_term": "CAST(NULL AS STRING)", "data_class": lit(a.data_class),
                "definition": lit(a.definition), "expected_signature": "CAST(NULL AS STRING)",
                "criticality": lit(ka.CRITICALITY), "pii": lit(a.pii),
                "regulatory_basis": "CAST(NULL AS STRING)",
                "tolerance_pct": "CAST(NULL AS DOUBLE)", "bindings": binding,
                "business_domain": lit(a.domain), "owner_group": lit(ka.OWNER_GROUP),
                "status": "'registered'", "effective_from": "current_timestamp()",
                "registered_by": "current_user()", "registered_at": "current_timestamp()",
                "note": lit(note)}
        add(f"cde:{a.cde_id}", "insert",
            f"INSERT INTO {cde} ({', '.join(CDE_COLUMNS)})\n"
            f"SELECT " + ",\n       ".join(vals[c] for c in CDE_COLUMNS) + "\n"
            f"WHERE  NOT EXISTS (SELECT 1 FROM {cde} WHERE cde_id = {lit(a.cde_id)})",
            [f"-- {a.cde_id}  {a.table.split('.')[-1]}.{a.column}"])

    # --- Part 5 -----------------------------------------------------------------------
    lines += ["", "-- =====================================================================",
              f"-- Part 5 — {len(rules)} rules, rule_version 1, status shadow",
              "-- ====================================================================="]
    for r in rules:
        vals = {"rule_id": lit(r.rule_id), "rule_version": "1", "rule_name": lit(r.rule_name),
                "target_table": lit(r.table), "target_column": lit(r.column),
                "cde_id": lit(r.cde_id), "rule_type": lit(r.rule_type),
                "rule_expr": lit(r.rule_expr),
                "scope_filter": lit(r.scope_filter) if r.scope_filter else "CAST(NULL AS STRING)",
                "join_sql": "CAST(NULL AS STRING)",
                # Thresholds live on rules (2026-10-22), seeded from the attribute's tolerance.
                "fail_threshold_pct": f"CAST({float(ka.TOLERANCE[r.cde_id])!r} AS DOUBLE)",
                "severity": lit(r.severity), "business_domain": lit(ka.TABLE_DOMAIN[r.table]),
                "owner_group": lit(ka.OWNER_GROUP), "source_layer": "'L2'",
                "status": "'shadow'", "effective_from": "current_timestamp()",
                "created_by": "current_user()", "created_at": "current_timestamp()",
                "promoted_by": _null("promoted_by"), "promoted_at": _null("promoted_at"),
                "note": lit(r.note)}
        add(f"rule:{r.rule_id}", "insert",
            f"INSERT INTO {reg} ({', '.join(RULE_COLUMNS)})\n"
            f"SELECT " + ",\n       ".join(vals[c] for c in RULE_COLUMNS) + "\n"
            f"WHERE  NOT EXISTS (SELECT 1 FROM {reg} WHERE rule_id = {lit(r.rule_id)})",
            [f"-- {r.rule_id}  [{r.rule_type}, {r.severity}]"])

    # --- Part 6 -----------------------------------------------------------------------
    lines += ["", "-- =====================================================================",
              f"-- Part 6 — select the {len(ka.TABLES)} source tables",
              "-- ====================================================================="]
    for t in ka.TABLES:
        vals = {"target_table": lit(t), "table_version": "1", "table_code": lit(ka.TABLE_CODE[t]),
                "row_key": "array(" + ", ".join(lit(k) for k in ka.ROW_KEY[t]) + ")",
                "owner_group": lit(ka.OWNER_GROUP), "business_domain": lit(ka.TABLE_DOMAIN[t]),
                "schedule_group": "'daily_0300'", "scan_mode": "'full'", "status": "'selected'",
                "effective_from": "current_timestamp()", "selected_by": "current_user()",
                "note": lit("Selected 2026-10-12 as a key-attribute source table. "
                            + ka.LATEST_RECORD_GAP)}
        for c in MONITORED_COLUMNS:
            vals.setdefault(c, _null(c))
        add(f"table:{t}", "insert",
            f"INSERT INTO {mon} ({', '.join(MONITORED_COLUMNS)})\n"
            f"SELECT " + ",\n       ".join(vals[c] for c in MONITORED_COLUMNS) + "\n"
            f"WHERE  NOT EXISTS (SELECT 1 FROM {mon} WHERE target_table = {lit(t)})",
            [f"-- {t}  as {ka.TABLE_CODE[t]}, row key {ka.ROW_KEY[t]}"])

    # --- Checks -----------------------------------------------------------------------
    lines += ["", "-- =====================================================================",
              "-- Part 7 — verification, read-only",
              "-- ====================================================================="]
    add("7a", "check",
        f"SELECT CASE WHEN cde_id LIKE {KA_LIKE} THEN 'key attribute' ELSE 'mock' END AS kind,\n"
        f"       status, COUNT(*) AS elements\nFROM   {cde_cur}\nGROUP  BY 1, 2 ORDER BY 1, 2",
        [f"-- 7a — EXPECTED: one row, key attribute / registered / {len(ka.KEY_ATTRIBUTES)}.",
         "-- (The current view drops nothing: a retired element shows as retired here.)"])
    add("7b", "check",
        f"SELECT status, COUNT(*) AS rules,\n"
        f"       SUM(CASE WHEN cde_id LIKE {KA_LIKE} THEN 1 ELSE 0 END) AS on_key_attributes\n"
        f"FROM   {reg_cur} GROUP BY status ORDER BY status",
        [f"-- 7b — EXPECTED: shadow {len(rules)}, every one on a key attribute; nothing active;",
         "-- the rest retired."])
    add("7c", "check",
        "SELECT r.rule_id\n"
        f"FROM   {reg_cur} r\n"
        "LEFT JOIN (SELECT c.cde_id, b.target_table, b.target_column\n"
        f"           FROM {cde_cur} c LATERAL VIEW explode(c.bindings) x AS b\n"
        "           WHERE c.status = 'registered' AND b.binding_status = 'bound') e\n"
        "  ON  e.cde_id = r.cde_id AND e.target_table = r.target_table\n"
        "  AND e.target_column = r.target_column\n"
        "WHERE r.status <> 'retired' AND e.cde_id IS NULL",
        ["-- 7c — EXPECTED: zero rows. Every live rule names a key attribute binding its column."])
    add("7d", "check",
        f"SELECT target_table, table_version, status FROM {mon_cur} ORDER BY status, target_table",
        [f"-- 7d — EXPECTED: the {len(ka.TABLES)} prod.* tables selected, every other table retired."])
    add("7e", "check",
        f"SELECT coverage_gap, COUNT(*) AS bindings FROM {cov} GROUP BY coverage_gap ORDER BY 1",
        [f"-- 7e — EXPECTED: no_rule {len(ka.KEY_ATTRIBUTES)}. Shadow rules do not count as coverage;",
         "-- a binding reads covered once its rules are promoted."])
    return lines, stmts


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", default="workspace")
    ap.add_argument("--schema", default="dq_triage")
    ap.add_argument("--prefix", default="dq_")
    a = ap.parse_args()
    lines, stmts = build(a.catalog, a.schema, a.prefix)
    (OUT / "migrate_key_attributes.sql").write_text("\n".join(lines) + "\n")
    n = sum(k == "insert" for _, k, _ in stmts)
    print(f"wrote sql/out/migrate_key_attributes.sql — {n} INSERTs "
          f"(3 retirements, {len(ka.KEY_ATTRIBUTES)} attributes, "
          f"{n - 3 - len(ka.KEY_ATTRIBUTES) - len(ka.TABLES)} rules, {len(ka.TABLES)} tables), "
          f"{len(stmts) - n} read-only checks")
    print("\nNOT RUN.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
