#!/usr/bin/env python3
"""Point the key attributes at a source catalog: the mock tables now, prod later.

    python3 sql/migrate_key_attributes_source.py --source-catalog workspace
    python3 sql/migrate_key_attributes_source.py --source-catalog prod      # back again

Writes sql/out/migrate_key_attributes_source_<catalog>.sql. The register names its
tables canonically (key_attributes/register.py: prod.udp_brnz_nrt_tech_view.*); this
moves only the catalog, the way sql/seed.py rewrites prod.customer.* onto the mock
tables. Schema and table names stay, so the mock tables key_attributes/mocksource.py
builds in `workspace` are found under the same names.

Three parts, all appends:

1. A new cde_version per attribute whose binding is not on the target catalog yet,
   with the binding rewritten and everything else carried forward.
2. A new rule_version per current key-attribute rule not on the target catalog yet,
   target_table rewritten. Status carries forward, so a shadow rule stays shadow and an
   active one stays active -- re-pointing is not a promotion.
3. The source tables: the ones on another catalog decommissioned (with a note), the
   target ones selected -- inserted at version 1, or selected again at their next
   version if they were decommissioned before. Table codes are never reused, so the
   mock tables carry their own (KAW_CONTACT, ...), and a prod table selected again
   keeps the code it had.

RE-RUNNABLE: every statement is guarded on the state it changes. NOT RUN by this script.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).parent.parent
OUT = pathlib.Path(__file__).parent / "out"
sys.path.insert(0, str(ROOT / "key_attributes"))
sys.path.insert(0, str(pathlib.Path(__file__).parent))

import register as ka  # noqa: E402
from migrate_cde_scope import CDE_COLUMNS, RULE_COLUMNS, lit  # noqa: E402
from migrate_key_attributes import KA_LIKE, MONITORED_COLUMNS, _null  # noqa: E402


def on(table: str, catalog: str) -> str:
    return catalog + table[table.index("."):]


def code(table: str, catalog: str) -> str:
    c = ka.TABLE_CODE[table]
    return c if catalog == "prod" else c.replace("KA_", f"KA{catalog[:1].upper()}_", 1)


def build(source_catalog: str, catalog: str, schema: str, prefix: str
          ) -> tuple[list[str], list[tuple[str, str, str]]]:
    q = f"{catalog}.{schema}.{prefix}"
    cde, cde_cur = f"{q}config_cde_registry", f"{q}config_v_cde_registry_current"
    reg, reg_cur = f"{q}config_rule_registry", f"{q}config_v_rule_registry_current"
    mon, mon_cur = f"{q}config_monitored_table", f"{q}config_v_monitored_table_current"
    targets = [on(t, source_catalog) for t in ka.TABLES]
    every = sorted({on(t, c) for t in ka.TABLES for c in ("prod", source_catalog)})
    others = [t for t in every if t not in targets]
    mock = source_catalog != "prod"

    stmts: list[tuple[str, str, str]] = []
    lines = [
        "-- =====================================================================",
        f"-- migrate_key_attributes_source_{source_catalog}.sql — GENERATED by",
        "-- sql/migrate_key_attributes_source.py. Do not edit.",
        f"-- target: {catalog}.{schema}, prefix {prefix}",
        "--",
        f"-- Points the 22 key attributes, their rules and their source tables at the",
        f"-- {source_catalog} catalog"
        + (" -- the MOCK tables built by key_attributes/mocksource.py." if mock else "."),
        "-- Every statement is guarded: re-running inserts nothing.",
        "-- =====================================================================",
    ]

    def add(label, kind, sql, comment=None):
        stmts.append((label, kind, sql))
        lines.extend(["", *(comment or []), sql + ";"])

    why = ("MOCK source tables in workspace, because prod is not reachable from this "
           "workspace" if mock else "the real source tables")
    lines += ["", f"-- Part 1 — {len(ka.KEY_ATTRIBUTES)} attributes"]
    for a in ka.KEY_ATTRIBUTES:
        t = on(a.table, source_catalog)
        binding = ("array(named_struct('target_table', {t}, 'target_column', {c}, "
                   "'populated_when', {p}, 'expected_scope_filter', CAST(NULL AS STRING), "
                   "'binding_status', 'bound', 'discovered_by', 'manual', "
                   "'confidence', CAST(1.0 AS DOUBLE)))").format(
            t=lit(t), c=lit(a.column),
            p=lit(a.populated_when) if a.populated_when else "CAST(NULL AS STRING)")
        note = f"Binding moved to {t}: {why}. Nothing else changed."
        sel = [{"cde_version": "c.cde_version + 1", "bindings": binding,
                "effective_from": "current_timestamp()", "registered_at": "current_timestamp()",
                "registered_by": "current_user()", "note": lit(note)}.get(col, f"c.{col}")
               for col in CDE_COLUMNS]
        add(f"cde:{a.cde_id}", "insert",
            f"INSERT INTO {cde} ({', '.join(CDE_COLUMNS)})\n"
            f"SELECT {', '.join(sel)}\nFROM   {cde} c\n"
            f"WHERE  c.cde_id = {lit(a.cde_id)}\n"
            f"  AND  c.cde_version = (SELECT max(cde_version) FROM {cde} WHERE cde_id = {lit(a.cde_id)})\n"
            f"  AND  c.status <> 'retired'\n"
            f"  AND  NOT array_contains(transform(c.bindings, b -> b.target_table), {lit(t)})")

    lines += ["", "-- Part 2 — every current key-attribute rule, one statement per table"]
    for src in ka.TABLES:
        t = on(src, source_catalog)
        note = f"Re-pointed at {t}: {why}. Same rule, same status."
        sel = [{"rule_version": "r.rule_version + 1", "target_table": lit(t),
                "effective_from": "current_timestamp()", "created_at": "current_timestamp()",
                "created_by": "current_user()", "note": lit(note)}.get(col, f"r.{col}")
               for col in RULE_COLUMNS]
        src_names = ", ".join(lit(on(src, c)) for c in ("prod", source_catalog) if on(src, c) != t)
        add(f"rules:{src.split('.')[-1]}", "insert",
            f"INSERT INTO {reg} ({', '.join(RULE_COLUMNS)})\n"
            f"SELECT {', '.join(sel)}\nFROM   {reg} r\n"
            f"JOIN   (SELECT rule_id AS id, max(rule_version) AS v FROM {reg} GROUP BY rule_id) m\n"
            f"  ON   m.id = r.rule_id AND m.v = r.rule_version\n"
            f"WHERE  r.status <> 'retired' AND r.cde_id LIKE {KA_LIKE}\n"
            f"  AND  r.target_table IN ({src_names})")

    lines += ["", "-- Part 3 — the source tables"]
    if others:
        sel = []
        for col in MONITORED_COLUMNS:
            sel.append({"table_version": "t.table_version + 1", "status": "'retired'",
                        "effective_from": "current_timestamp()", "selected_by": "current_user()",
                        "note": lit(f"Decommissioned: the key attributes now read {source_catalog} "
                                    f"({why})."),
                        "slice_change": "CAST(NULL AS STRING)"}.get(col, f"t.{col}"))
        add("retire:other-catalog", "insert",
            f"INSERT INTO {mon} ({', '.join(MONITORED_COLUMNS)})\n"
            f"SELECT {', '.join(sel)}\nFROM   {mon} t\n"
            f"JOIN   (SELECT target_table AS id, max(table_version) AS v FROM {mon} GROUP BY target_table) m\n"
            f"  ON   m.id = t.target_table AND m.v = t.table_version\n"
            f"WHERE  t.status <> 'retired' AND t.target_table IN ({', '.join(lit(x) for x in others)})")
    for src in ka.TABLES:
        t = on(src, source_catalog)
        note = (f"Selected as a key-attribute source table ({why}). " + ka.LATEST_RECORD_GAP)
        vals = {"target_table": lit(t), "table_version": "1", "table_code": lit(code(src, source_catalog)),
                "row_key": "array(" + ", ".join(lit(k) for k in ka.ROW_KEY[src]) + ")",
                "owner_group": lit(ka.OWNER_GROUP), "business_domain": lit(ka.TABLE_DOMAIN[src]),
                "schedule_group": "'daily_0300'", "scan_mode": "'full'", "status": "'selected'",
                "effective_from": "current_timestamp()", "selected_by": "current_user()",
                "note": lit(note)}
        for col in MONITORED_COLUMNS:
            vals.setdefault(col, _null(col))
        add(f"select:{t}", "insert",
            f"INSERT INTO {mon} ({', '.join(MONITORED_COLUMNS)})\n"
            f"SELECT " + ",\n       ".join(vals[c] for c in MONITORED_COLUMNS) + "\n"
            f"WHERE  NOT EXISTS (SELECT 1 FROM {mon} WHERE target_table = {lit(t)})",
            [f"-- {t} as {code(src, source_catalog)}"])
        again = [{"table_version": "t.table_version + 1", "status": "'selected'",
                  "effective_from": "current_timestamp()", "selected_by": "current_user()",
                  "note": lit(note), "slice_change": "CAST(NULL AS STRING)",
                  "slice_proposed_filter": "CAST(NULL AS STRING)",
                  "slice_proposed_spec": "CAST(NULL AS STRING)",
                  "slice_proposed_by": "CAST(NULL AS STRING)"}.get(col, f"t.{col}")
                 for col in MONITORED_COLUMNS]
        add(f"reselect:{t}", "insert",
            f"INSERT INTO {mon} ({', '.join(MONITORED_COLUMNS)})\n"
            f"SELECT {', '.join(again)}\nFROM   {mon} t\n"
            f"WHERE  t.target_table = {lit(t)}\n"
            f"  AND  t.table_version = (SELECT max(table_version) FROM {mon} WHERE target_table = {lit(t)})\n"
            f"  AND  t.status = 'retired'",
            ["-- ...or selected again, keeping its code, if it was decommissioned before"])

    lines += ["", "-- Part 4 — verification, read-only"]
    add("4a", "check",
        f"SELECT target_table, status, COUNT(*) AS rules FROM {reg_cur}\n"
        f"WHERE  cde_id LIKE {KA_LIKE} GROUP BY 1, 2 ORDER BY 1, 2",
        [f"-- 4a — EXPECTED: every rule on a {source_catalog}.* table."])
    add("4b", "check",
        f"SELECT b.target_table, COUNT(*) AS attributes FROM {cde_cur} c\n"
        "LATERAL VIEW explode(c.bindings) x AS b\n"
        f"WHERE  c.cde_id LIKE {KA_LIKE} GROUP BY 1 ORDER BY 1",
        [f"-- 4b — EXPECTED: 22 bindings, all on {source_catalog}.*."])
    add("4c", "check",
        f"SELECT target_table, table_code, table_version, status FROM {mon_cur}\n"
        f"WHERE  target_table IN ({', '.join(lit(x) for x in every)}) ORDER BY status, target_table",
        [f"-- 4c — EXPECTED: the {source_catalog} tables selected, the others retired."])
    return lines, stmts


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source-catalog", required=True)
    ap.add_argument("--catalog", default="workspace")
    ap.add_argument("--schema", default="dq_triage")
    ap.add_argument("--prefix", default="dq_")
    a = ap.parse_args()
    lines, stmts = build(a.source_catalog, a.catalog, a.schema, a.prefix)
    path = OUT / f"migrate_key_attributes_source_{a.source_catalog}.sql"
    path.write_text("\n".join(lines) + "\n")
    n = sum(k == "insert" for _, k, _ in stmts)
    print(f"wrote {path.relative_to(ROOT)} — {n} guarded INSERTs, {len(stmts) - n} checks\n\nNOT RUN.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
