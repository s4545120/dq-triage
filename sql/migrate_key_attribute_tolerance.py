#!/usr/bin/env python3
"""Declare a tolerance on every key attribute: placeholders, not the business's.

    python3 sql/migrate_key_attribute_tolerance.py

Writes sql/out/migrate_key_attribute_tolerance.sql. One new cde_version per attribute
whose current tolerance_pct differs from key_attributes/register.TOLERANCE, everything
else carried forward and the note saying the number is a placeholder. A changed
tolerance changes the attribute's target and which of its breaches Triage holds back
(v_check_escalation); it changes no rule's fail_threshold_pct.

This writes the register directly, as every key-attribute migration has: the Elements
approval path (17/18) is not installed in dq_triage.

RE-RUNNABLE: each INSERT is guarded on the tolerance it sets. NOT RUN by this script.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).parent.parent
OUT = pathlib.Path(__file__).parent / "out"
sys.path.insert(0, str(ROOT / "key_attributes"))
sys.path.insert(0, str(pathlib.Path(__file__).parent))

import register as ka  # noqa: E402
from migrate_cde_scope import CDE_COLUMNS, lit  # noqa: E402
from migrate_key_attributes import KA_LIKE  # noqa: E402


def build(catalog: str, schema: str, prefix: str
          ) -> tuple[list[str], list[tuple[str, str, str]]]:
    q = f"{catalog}.{schema}.{prefix}"
    cde, cde_cur = f"{q}config_cde_registry", f"{q}config_v_cde_registry_current"
    stmts: list[tuple[str, str, str]] = []
    lines = [
        "-- =====================================================================",
        "-- migrate_key_attribute_tolerance.sql — GENERATED by",
        "-- sql/migrate_key_attribute_tolerance.py. Do not edit.",
        f"-- target: {catalog}.{schema}, prefix {prefix}",
        "--",
        "-- Declares a PLACEHOLDER tolerance on each of the 22 key attributes.",
        "-- Every statement is guarded: re-running inserts nothing.",
        "-- =====================================================================",
    ]

    def add(label, kind, sql, comment=None):
        stmts.append((label, kind, sql))
        lines.extend(["", *(comment or []), sql + ";"])

    lines += ["", f"-- Part 1 — {len(ka.KEY_ATTRIBUTES)} attributes"]
    for a in ka.KEY_ATTRIBUTES:
        tol = float(ka.TOLERANCE[a.cde_id])
        sel = [{"cde_version": "c.cde_version + 1",
                "tolerance_pct": f"CAST({tol!r} AS DOUBLE)",
                "effective_from": "current_timestamp()", "registered_at": "current_timestamp()",
                "registered_by": "current_user()",
                "note": lit(f"Tolerance {tol:g}%. {ka.TOLERANCE_NOTE}")}.get(col, f"c.{col}")
               for col in CDE_COLUMNS]
        add(f"cde:{a.cde_id}", "insert",
            f"INSERT INTO {cde} ({', '.join(CDE_COLUMNS)})\n"
            f"SELECT {', '.join(sel)}\nFROM   {cde} c\n"
            f"WHERE  c.cde_id = {lit(a.cde_id)}\n"
            f"  AND  c.cde_version = (SELECT max(cde_version) FROM {cde} WHERE cde_id = {lit(a.cde_id)})\n"
            f"  AND  c.status <> 'retired'\n"
            f"  AND  NOT (c.tolerance_pct <=> CAST({tol!r} AS DOUBLE))",
            [f"-- {a.cde_id}: {tol:g}%"])

    lines += ["", "-- Part 2 — verification, read-only"]
    add("2a", "check",
        f"SELECT tolerance_pct, COUNT(*) AS attributes FROM {cde_cur}\n"
        f"WHERE  cde_id LIKE {KA_LIKE} GROUP BY 1 ORDER BY 1",
        ["-- 2a — EXPECTED: 0.0 x3, 0.5 x3, 1.0 x2, 2.0 x5, 5.0 x9; no NULL."])
    return lines, stmts


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", default="workspace")
    ap.add_argument("--schema", default="dq_triage")
    ap.add_argument("--prefix", default="dq_")
    a = ap.parse_args()
    lines, stmts = build(a.catalog, a.schema, a.prefix)
    path = OUT / "migrate_key_attribute_tolerance.sql"
    path.write_text("\n".join(lines) + "\n")
    n = sum(k == "insert" for _, k, _ in stmts)
    print(f"wrote {path.relative_to(ROOT)} — {n} guarded INSERTs, {len(stmts) - n} checks\n\nNOT RUN.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
