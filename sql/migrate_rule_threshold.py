#!/usr/bin/env python3
"""Put each key attribute's tolerance onto its rules as the rule's own threshold.

    python3 sql/migrate_rule_threshold.py

Writes sql/out/migrate_rule_threshold.sql. Since 2026-10-22 a threshold lives on the rule
only (`config.rule_registry.fail_threshold_pct`): a rule breaches when its failure rate is
above it, every breach escalates, and nothing above a rule (attribute, domain, overall)
has a threshold. The values are seeded from the attribute's placeholder tolerance
(key_attributes/register.TOLERANCE), so they are still placeholders, now per rule.

One set-based INSERT: a new rule_version for every current, non-retired rule on a key
attribute whose limit differs from the attribute's tolerance, everything else carried
forward (status, scope, promotion). Shadow stays shadow.

RE-RUNNABLE: guarded on the limit it sets, so a second run inserts nothing. NOT RUN by
this script.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).parent.parent
OUT = pathlib.Path(__file__).parent / "out"
sys.path.insert(0, str(pathlib.Path(__file__).parent))

from migrate_cde_scope import RULE_COLUMNS, lit  # noqa: E402
from migrate_key_attributes import KA_LIKE  # noqa: E402

NOTE = ("Threshold set from the key attribute's tolerance: thresholds live on rules "
        "since 2026-10-22. Placeholder, not business-approved.")


def build(catalog: str, schema: str, prefix: str) -> tuple[list[str], list[tuple[str, str, str]]]:
    q = f"{catalog}.{schema}.{prefix}"
    reg, cde_cur = f"{q}config_rule_registry", f"{q}config_v_cde_registry_current"
    stmts: list[tuple[str, str, str]] = []
    lines = [
        "-- =====================================================================",
        "-- migrate_rule_threshold.sql — GENERATED by sql/migrate_rule_threshold.py.",
        f"-- target: {catalog}.{schema}, prefix {prefix}",
        "--",
        "-- Each key-attribute rule's threshold = its attribute's tolerance.",
        "-- Guarded: re-running inserts nothing.",
        "-- =====================================================================",
    ]

    def add(label, kind, sql, comment=None):
        stmts.append((label, kind, sql))
        lines.extend(["", *(comment or []), sql + ";"])

    cols = RULE_COLUMNS + ["template_id", "template_version",  # 01 gained these on 2026-10-06
                           "function_source", "function_name"]  # and these on 2026-10-23
    sel = []
    for col in cols:
        sel.append({
            "rule_version": "r.rule_version + 1",
            "fail_threshold_pct": "CAST(c.tolerance_pct AS DOUBLE)",
            "effective_from": "current_timestamp()",
            "created_by": "current_user()",
            "created_at": "current_timestamp()",
            "note": lit(NOTE),
        }.get(col, f"r.{col}"))
    add("rules", "insert",
        f"INSERT INTO {reg} ({', '.join(cols)})\n"
        f"SELECT {', '.join(sel)}\n"
        f"FROM (SELECT x.*, ROW_NUMBER() OVER (PARTITION BY x.rule_id ORDER BY x.rule_version DESC) AS rn\n"
        f"      FROM {reg} x) r\n"
        f"JOIN {cde_cur} c ON c.cde_id = r.cde_id\n"
        f"WHERE r.rn = 1 AND r.status <> 'retired' AND r.cde_id LIKE {KA_LIKE}\n"
        f"  AND c.tolerance_pct IS NOT NULL\n"
        f"  AND NOT (r.fail_threshold_pct <=> CAST(c.tolerance_pct AS DOUBLE))",
        ["-- Part 1 — one new version per rule whose limit differs from its attribute's tolerance"])
    add("2a", "check",
        f"SELECT r.fail_threshold_pct, r.status, COUNT(*) AS rules\n"
        f"FROM {q}config_v_rule_registry_current r\n"
        f"WHERE r.cde_id LIKE {KA_LIKE} AND r.status <> 'retired' GROUP BY 1, 2 ORDER BY 1, 2",
        ["-- 2a — EXPECTED: every limit one of the attribute tolerances (0, 0.5, 1, 2, 5)."])
    return lines, stmts


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", default="workspace")
    ap.add_argument("--schema", default="dq_triage")
    ap.add_argument("--prefix", default="dq_")
    a = ap.parse_args()
    lines, stmts = build(a.catalog, a.schema, a.prefix)
    path = OUT / "migrate_rule_threshold.sql"
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path.relative_to(ROOT)} — {len(stmts)} statements\n\nNOT RUN.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
