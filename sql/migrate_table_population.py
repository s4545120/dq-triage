#!/usr/bin/env python3
"""Declare the current record on the key-attribute source tables.

    python3 sql/migrate_table_population.py --source-catalog workspace

Writes sql/out/migrate_table_population_<catalog>.sql: one guarded INSERT per source
table into config.table_population (sql/ddl/21), then read-only checks. The table
itself, and check_run's two population columns, come from `onboard.py install`, which
renders 21 and adds the columns; run that first.

What is declared, and why: every key-attribute table is a CDC history table carrying
ECF_NSRT_TS / SCN / offset / OP_TYPE (key_attributes/mocksource.py builds them that way,
after the real views the analysis queries read). The current record is the newest
version by those three, and OP_TYPE = 'D' marks a deletion. The record key is
key_attributes/register.ROW_KEY. On the real tables the three version columns' types
are unconfirmed: a STRING SCN of varying length sorts as text, which is why
ECF_NSRT_TS leads.

RE-RUNNABLE: an INSERT is skipped when the table already has a declaration. NOT RUN.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).parent.parent
OUT = pathlib.Path(__file__).parent / "out"
sys.path.insert(0, str(ROOT / "key_attributes"))
sys.path.insert(0, str(pathlib.Path(__file__).parent))

import register as ka  # noqa: E402
from migrate_cde_scope import lit  # noqa: E402
from migrate_key_attributes_source import on  # noqa: E402

VERSION_BY = ["ECF_NSRT_TS", "SCN", "offset"]
NOTE = ("CDC history table: the current record is the newest version by ECF_NSRT_TS, "
        "SCN, offset, and OP_TYPE = 'D' is a deletion. Closes LATEST_RECORD_GAP for the "
        "latest-version half; migration scope is still a slice to declare.")


def arr(xs: list[str]) -> str:
    return "array(" + ", ".join(lit(x) for x in xs) + ")"


def build(source_catalog: str, catalog: str, schema: str, prefix: str) -> list[str]:
    pop = f"{catalog}.{schema}.{prefix}config_table_population"
    lines = [f"-- GENERATED by sql/migrate_table_population.py — the current record on the "
             f"{source_catalog} key-attribute tables.",
             f"-- Target: {catalog}.{schema}. Run `onboard.py --schema {schema} install` first.",
             "-- NOT RUN by the generator. EXPLAIN each statement, then run in order.", ""]
    for i, t in enumerate(ka.TABLES, 1):
        tab = on(t, source_catalog)
        lines += [f"-- 1{chr(96 + i)} — {tab}",
                  f"INSERT INTO {pop} (target_table, population_version, record_key, version_by,\n"
                  f"                   deleted_column, deleted_value, effective_from, declared_by, note)\n"
                  f"SELECT {lit(tab)}, 1, {arr(ka.ROW_KEY[t])}, {arr(VERSION_BY)},\n"
                  f"       'OP_TYPE', 'D', current_timestamp(), current_user(), {lit(NOTE)}\n"
                  f"WHERE  NOT EXISTS (SELECT 1 FROM {pop} WHERE target_table = {lit(tab)});", ""]
    lines += ["-- 2 — check, read-only. EXPECTED: five rows, version 1, OP_TYPE / D.",
              f"SELECT target_table, population_version, record_key, version_by, deleted_column,\n"
              f"       deleted_value FROM {pop} ORDER BY target_table;", ""]
    return lines


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source-catalog", required=True)
    ap.add_argument("--catalog", default="workspace")
    ap.add_argument("--schema", default="dq_triage")
    ap.add_argument("--prefix", default="dq_")
    a = ap.parse_args()
    path = OUT / f"migrate_table_population_{a.source_catalog}.sql"
    path.write_text("\n".join(build(a.source_catalog, a.catalog, a.schema, a.prefix)))
    print(f"wrote {path.relative_to(ROOT)} — {len(ka.TABLES)} guarded INSERTs, 1 check\n\nNOT RUN.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
