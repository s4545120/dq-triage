#!/usr/bin/env python3
"""Set every key attribute's business domain to the one key_attributes/register.py names.

    python3 sql/migrate_key_attribute_domain.py

Writes sql/out/migrate_key_attribute_domain.sql. One new cde_version per attribute
whose current business_domain differs from register.TABLE_DOMAIN (all Consumer since
2026-10-19), everything else carried forward. The dashboard filters and groups on the
attribute's domain, read off v_cde_registry_current.

Rules and monitored tables keep the domain they were written with: a rule version
that changes only a label is a version a reader hunts through for a difference, and
nothing on the stage-1 dashboard reads the rule's copy.

RE-RUNNABLE: each INSERT is guarded on the domain it sets. NOT RUN by this script.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).parent.parent
OUT = pathlib.Path(__file__).parent / "out"
sys.path.insert(0, str(ROOT / "key_attributes"))
sys.path.insert(0, str(pathlib.Path(__file__).parent))

import register as ka  # noqa: E402
from migrate_cde_scope import CDE_COLUMNS, lit  # noqa: E402
from migrate_key_attributes import KA_LIKE  # noqa: E402


def build(catalog: str, schema: str, prefix: str
          ) -> tuple[list[str], list[tuple[str, str, str]]]:
    q = f"{catalog}.{schema}.{prefix}"
    cde, cde_cur = f"{q}config_cde_registry", f"{q}config_v_cde_registry_current"
    stmts: list[tuple[str, str, str]] = []
    lines = [
        "-- =====================================================================",
        "-- migrate_key_attribute_domain.sql — GENERATED by",
        "-- sql/migrate_key_attribute_domain.py. Do not edit.",
        f"-- target: {catalog}.{schema}, prefix {prefix}",
        "--",
        "-- Sets the business domain of each of the 22 key attributes.",
        "-- Every statement is guarded: re-running inserts nothing.",
        "-- =====================================================================",
    ]

    def add(label, kind, sql, comment=None):
        stmts.append((label, kind, sql))
        lines.extend(["", *(comment or []), sql + ";"])

    lines += ["", f"-- Part 1 — {len(ka.KEY_ATTRIBUTES)} attributes"]
    for a in ka.KEY_ATTRIBUTES:
        sel = [{"cde_version": "c.cde_version + 1",
                "business_domain": lit(a.domain),
                "effective_from": "current_timestamp()", "registered_at": "current_timestamp()",
                "registered_by": "current_user()",
                "note": lit(f"Business domain {a.domain}. Every key attribute is "
                            f"{a.domain} for now; nothing else changed.")}.get(col, f"c.{col}")
               for col in CDE_COLUMNS]
        add(f"cde:{a.cde_id}", "insert",
            f"INSERT INTO {cde} ({', '.join(CDE_COLUMNS)})\n"
            f"SELECT {', '.join(sel)}\nFROM   {cde} c\n"
            f"WHERE  c.cde_id = {lit(a.cde_id)}\n"
            f"  AND  c.cde_version = (SELECT max(cde_version) FROM {cde} WHERE cde_id = {lit(a.cde_id)})\n"
            f"  AND  c.status <> 'retired'\n"
            f"  AND  NOT (c.business_domain <=> {lit(a.domain)})",
            [f"-- {a.cde_id}: {a.domain}"])

    lines += ["", "-- Part 2 — verification, read-only"]
    add("2a", "check",
        f"SELECT business_domain, COUNT(*) AS attributes FROM {cde_cur}\n"
        f"WHERE  cde_id LIKE {KA_LIKE} GROUP BY 1 ORDER BY 1",
        [f"-- 2a — EXPECTED: Consumer x{len(ka.KEY_ATTRIBUTES)}."])
    return lines, stmts


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", default="workspace")
    ap.add_argument("--schema", default="dq_triage")
    ap.add_argument("--prefix", default="dq_")
    a = ap.parse_args()
    lines, stmts = build(a.catalog, a.schema, a.prefix)
    path = OUT / "migrate_key_attribute_domain.sql"
    path.write_text("\n".join(lines) + "\n")
    n = sum(k == "insert" for _, k, _ in stmts)
    print(f"wrote {path.relative_to(ROOT)} — {n} guarded INSERTs, {len(stmts) - n} checks\n\nNOT RUN.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
